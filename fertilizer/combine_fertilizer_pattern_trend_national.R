        sink(type = "message")
        close(fp)
        return(NULL)
      }
    }
    if (!exists("trend_admin_raster")) {
      # Unwrap on parallel nodes
      trend_admin_raster <- terra::unwrap(trend_admin_raster_wrapped)
    }
    cat("***", pcrop, "***\n")
