        tmp_res <- ifelse(pattern_admin_res < 1 / 60, 3600, 60) *
          pattern_admin_res
        tmp_string <- paste(
          unique(round(tmp_res)),
          unique(ifelse(pattern_admin_res < 1 / 60, "sec", "min")),
          sep = "",
          collapse = "_by_"
        )
        working_dir_pattern <- file.path("tmp", paste0("work_", tmp_string))
        rm(tmp_res, tmp_string)
      } else {
