## Fill gaps in FAOSTAT production timeseries                                 ##
## This uses fill_timeseries() defined in helper/fill_timeseries.R            ##
## First, extend production_array if landuse_array covers more years          ##
if (
  length(
    setdiff(
      dimnames(faostat_env$landuse_array)[["time"]],
      dimnames(faostat_env$production_array)[["time"]]
    )
  ) > 0
) {
  years <- as.character(
    sort(
      as.integer(
        union(
          dimnames(faostat_env$landuse_array)[["time"]],
          dimnames(faostat_env$production_array)[["time"]]
        )
      )
    )
  )
  production_array_filled <- faostat_env$production_array[, , , years]
  dimnames(production_array_filled)[["time"]] <- years
} else {
  production_array_filled <- faostat_env$production_array
}
# production_array_gapfilling logs which cells have been gapfilled
rem_dim <- match("element", names(dim(production_array_filled)))
production_array_gapfilling <- array(
  FALSE,
  dim = dim(production_array_filled)[-rem_dim],
  dimnames = dimnames(production_array_filled)[-rem_dim]
)
# Informative print statements are logged to text file
logfile <- paste0(
  "gapfilling_FAOSTAT_country_level",
  add_version_string(LandInG_setup$landuse$fao_version_string),
  ".txt"
)

logfile <- ifelse(
  nchar(LandInG_setup$landuse$landuse_dir) > 0,
  file.path(
    LandInG_setup$landuse$landuse_dir,
    "tmp",
    logfile
  ),
  file.path(
    "tmp",
    logfile
  )
)
cat(
  "Gapfilling FAOSTAT production timeseries. See", sQuote(logfile),
  "for details.\n"
)
sink(file = logfile)
# Only gap-fill countries, not country groups
for (country in setdiff(
  dimnames(production_array_filled)[["country"]],
  names(fao_groups)
)) {
  if (country %in% dimnames(faostat_env$landuse_array)[["country"]]) {
    cat("*** Gap-filling FAOSTAT production data for", sQuote(country), "***\n")
    cropland <- fill_timeseries(
      faostat_env$landuse_array[country, "Cropland", "Area", ]
    )
    for (crop in seq_len(dim(faostat_env$production_array)[2])) {
      index <- match(
        dimnames(faostat_env$production_array)[["item"]][crop],
        faostat_env$production_items$NAME
      )
      if (faostat_env$production_items$CODE[index] > 1000) {
        # Item codes > 1000 are for groups
        # Skip summed groups (such as Cereals,Total)
        next
      }
      years <- dimnames(production_array_filled)[["time"]]
      production_array_filled[country, crop, "Area harvested", ] <-
        fill_timeseries(
          production_array_filled[country, crop, "Area harvested", ],
          cropland,
          dimnames(faostat_env$production_array)[["item"]][crop]
        )
      index <- which(
        production_array_filled[country, crop, "Area harvested", ] !=
          faostat_env$production_array[country, crop, "Area harvested", years]
      )
      production_array_gapfilling[country, crop, index] <- TRUE
      index <- which(
        is.na(
          faostat_env$production_array[country, crop, "Area harvested", years]
        ) & !is.na(production_array_filled[country, crop, "Area harvested", ])
      )
      production_array_gapfilling[country, crop, index] <- TRUE
    }
  }
}
sink()

# Update country groups based on gap-filled countries
for (country in intersect(
  dimnames(production_array_filled)[["country"]],
  names(fao_groups)
)) {
  group_country_names <- intersect(
    dimnames(production_array_filled)[["country"]],
    fao_groups[[country]]
  )
  index <- setdiff(
    dimnames(production_array_filled)[["item"]],
    fao_production_item_group_def$Item.Group
  )
  production_array_filled[country, index, "Area harvested", ] <-
    ifelse(
      apply(
        production_array_filled[group_country_names, index, "Area harvested", ],
        c(2, 3),
        function(indata) all(is.na(indata))
      ),
      NA,
      apply(
        production_array_filled[group_country_names, index, "Area harvested", ],
        c(2, 3),
        sum,
        na.rm = TRUE
      )
    )
  # Set gapfilling to TRUE if any country in the country group is gap-filled
  production_array_gapfilling[country, index, ] <- apply(
    production_array_gapfilling[group_country_names, index, ],
    c(2, 3),
    any,
    na.rm = TRUE
  )
}
