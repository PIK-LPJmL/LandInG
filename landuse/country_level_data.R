## Aggregate HYDE cropland to country scale for countries missing in FAOSTAT  ##
## (not all countries) and fill years included in landuse_array               ##
fill_countries <- union(
  setdiff(
    dimnames(fao_mon_production_array)[["country"]],
    dimnames(faostat_env$landuse_array)[["country"]]
  ),
  names(
    which(
      apply(
        faostat_env$landuse_array[, "Cropland", , ],
        "country",
        function(x) all(is.na(x))
      )
    )
  )
)
if (length(fill_countries) > 0) {
  cat(
    "GADM has", length(fill_countries),
    "countries not included in FAOSTAT.",
    "Deriving country-scale cropland extent from HYDE\n"
  )
  hyde_raster <- terra::rast(
    LandInG_setup$landuse$hyde_cropland_filename,
    lyrs = 1
  )
  if (matching_extent(
    terra::ext(hyde_raster),
    global_extent,
    terra::xres(hyde_raster),
    terra::yres(hyde_raster)
  )) {
    terra::ext(hyde_raster) <- global_extent
  }
  if (
    any(
      terra::res(hyde_raster) <
        terra::res(LandInG_setup$landuse$gadm_raster)
    )
  ) {
    hyde2gadm <- round(
      terra::res(LandInG_setup$landuse$gadm_raster) / terra::res(hyde_raster),
      4
    )
    if (max(hyde2gadm %% 1) != 0) {
      stop(
        "HYDE resolution ",
        toString(round(terra::res(hyde_raster), 5)),
        " is not an integer multiple of GADM resolution ",
        toString(round(terra::res(LandInG_setup$landuse$gadm_raster), 5))
      )
    }
  } else if (
    any(
      terra::res(hyde_raster) / terra::res(LandInG_setup$landuse$gadm_raster) >
        1.00001
    )
  ) {
    stop(
      "GADM resolution ",
      toString(round(terra::res(LandInG_setup$landuse$gadm_raster), 5)),
      " is too fine for HYDE resolution ",
      toString(round(terra::res(hyde_raster), 5)), ".\n",
      "You need to create a gridded GADM mask at the HYDE resolution."
    )
  } else {
    hyde2gadm <- c(1, 1)
  }

  cat(
    "HYDE", LandInG_setup$landuse$hyde_cropland_varname,
    "for", min(as.integer(dimnames(faostat_env$landuse_array)[["time"]])), "to",
    min(
      max(as.integer(dimnames(faostat_env$landuse_array)[["time"]])),
      max(LandInG_setup$landuse$hyde_period)
    ),
    "loaded from", sQuote(LandInG_setup$landuse$hyde_cropland_filename), "\n"
  )
  hyde_croplandfile <-
    ncdf4::nc_open(LandInG_setup$landuse$hyde_cropland_filename)
  lats <- hyde_croplandfile$dim$lat$vals
  raster_lats <- terra::yFromRow(hyde_raster)
  hyde_flip <- (lats[1] < lats[2]) != (raster_lats[1] < raster_lats[2])

  if (!matching_extent(
    terra::ext(hyde_raster),
    terra::ext(LandInG_setup$landuse$gadm_raster),
    terra::xres(LandInG_setup$landuse$gadm_raster),
    terra::yres(LandInG_setup$landuse$gadm_raster)
  )) {
    stop("Spatial extent of HYDE cropland does not match GADM extent")
  }
  if (
    units::ud_convert(
      1,
      LandInG_setup$landuse$hyde_area_units,
      hyde_croplandfile$var[[LandInG_setup$landuse$hyde_cropland_varname]]$units
    ) != 1
  ) {
    warning(
      "Unit in file ", sQuote(LandInG_setup$landuse$hyde_cropland_filename),
      " [",
      hyde_croplandfile$var[[LandInG_setup$landuse$hyde_cropland_varname]]$units,
      "] differs from defined hyde_area_units [",
      LandInG_setup$landuse$hyde_area_units,
      "].",
      call. = FALSE,
      immediate. = TRUE
    )
    # Update unit
    LandInG_setup$landuse$hyde_area_units <-
      hyde_croplandfile$var[[LandInG_setup$landuse$hyde_cropland_varname]]$units
    hyde_is_fraction <- !units::ud_are_convertible(
      LandInG_setup$landuse$hyde_area_units,
      "m2"
    )
  }
  load_period <- c(
    max(
      min(as.integer(dimnames(faostat_env$landuse_array)[["time"]])),
      min(LandInG_setup$landuse$hyde_period)
    ),
    min(
      max(as.integer(dimnames(faostat_env$landuse_array)[["time"]])),
      max(LandInG_setup$landuse$hyde_period)
    )
  )

  start_year <- load_period[1] - min(LandInG_setup$landuse$hyde_period) + 1
  count_year <- load_period[2] - load_period[1] + 1
  hyde_cropland <- ncdf4::ncvar_get(
    nc = hyde_croplandfile,
    varid = LandInG_setup$landuse$hyde_cropland_varname,
    start = c(1, 1, start_year),
    count = c(-1, -1, count_year)
  )
  dimnames(hyde_cropland)[[3]] <- seq(load_period[1], load_period[2])
  if (
    load_period[1] >
      min(as.integer(dimnames(faostat_env$landuse_array)[["time"]]))
  ) {
    # HYDE starts too late, extend at beginning
    hyde_cropland <- abind::abind(
      array(
        dim = c(
          dim(hyde_cropland)[- 3],
          load_period[1] -
            min(as.integer(dimnames(faostat_env$landuse_array)[["time"]]))
        ),
        dimnames <- list(
          NULL,
          NULL,
          seq(
            min(as.integer(dimnames(faostat_env$landuse_array)[["time"]])),
            load_period[1] - 1
          )
        )
      ),
      hyde_cropland,
      along = 3
    )
  }
  if (
    max(as.integer(dimnames(faostat_env$landuse_array)[["time"]])) >
      load_period[2]
  ) {
    hyde_cropland <- abind::abind(
      hyde_cropland,
      array(
        dim = c(
          dim(hyde_cropland)[-3],
          max(as.integer(dimnames(faostat_env$landuse_array)[["time"]])) -
            load_period[2]
        ),
        dimnames = list(NULL, NULL,
          seq(
            load_period[2] + 1,
            max(as.integer(dimnames(faostat_env$landuse_array)[["time"]]))
          )
        )
      ),
      along = 3
    )
  }
  hyde_cropland <-
    hyde_cropland[, , dimnames(faostat_env$landuse_array)[["time"]]]
  if (hyde_flip) {
    gc()
    hyde_cropland <- hyde_cropland[, seq(hyde_croplandfile$dim$lat$len, 1), ]
    gc()
  }
  if (hyde_is_fraction) {
    # Need to reload HYDE area at native HYDE resolution, not GADM resolution
    hyde_area <- load_hyde_area(
      filename = LandInG_setup$landuse$hyde_area_file,
      fileunits = LandInG_setup$landuse$hyde_area_file_units,
      return_units = LandInG_setup$landuse$fao_area_units,
      return_raster = hyde_raster,
      earth_radius = LandInG_setup$earthradius,
      gextent = global_extent
    )
    hyde_area <- hyde_area$area
    hyde_cropland <- hyde_cropland *
      units::ud_convert(1, LandInG_setup$landuse$hyde_area_units, "1") *
      terra::values(hyde_area, mat = FALSE)
  } else {
    hyde_cropland <- hyde_cropland * units::ud_convert(
      1,
      LandInG_setup$landuse$hyde_area_units,
      LandInG_setup$landuse$fao_area_units
    )
  }
  if (max(hyde2gadm) > 1) {
    cat("Aggregating HYDE cropland to GADM resolution\n")
    # Aggregate to GADM resolution
    hyde_cropland <- aggregate_array(hyde_cropland, hyde2gadm, "sum", FALSE)
  }
  # Dissolve separate lon and lat dimensions
  if (length(dim(hyde_cropland)) == 2) {
    dim(hyde_cropland) <- c(
      cell = ncol(hyde_cropland) * nrow(hyde_cropland),
      time = 1
    )
  } else {
    dim(hyde_cropland) <- c(
      cell = ncol(hyde_cropland) * nrow(hyde_cropland),
      time = dim(hyde_cropland)[3]
    )
  }
  dimnames(hyde_cropland) <- list(
    cell = NULL,
    time = dimnames(faostat_env$landuse_array)[["time"]]
  )
  landuse_array_expanded <- faostat_env$landuse_array
  cat("Aggregating countries\n")
  for (country in fill_countries) {
    if (!country %in% dimnames(landuse_array_expanded)[["country"]]) {
      # Add country to array
      landuse_array_expanded <- abind::abind(
        landuse_array_expanded,
        array(
          dim = c(country = 1, dim(landuse_array_expanded)[-1]),
          dimnames = c(
            country = list(country),
            dimnames(landuse_array_expanded)[-1]
          )
        ),
        along = 1,
        use.dnns = TRUE
      )
    }
    if (length(fao_gadm_country_cells[[country]]) > 1) {
      landuse_array_expanded[country, "Cropland", "Area", ] <- apply(
        hyde_cropland[fao_gadm_country_cells[[country]], ],
        "time",
        sum,
        na.rm = TRUE
      )
    } else if (length(fao_gadm_country_cells[[country]]) == 1) {
      landuse_array_expanded[country, "Cropland", "Area", ] <-
        hyde_cropland[fao_gadm_country_cells[[country]], ]
    }
  }
  # Restore dimension naming after abind
  dn <- dimnames(landuse_array_expanded)
  names(dim(landuse_array_expanded)) <- names(dn) <-
    names(dim(faostat_env$landuse_array))
  dimnames(landuse_array_expanded) <- dn
  rm(hyde_raster)
  ncdf4::nc_close(hyde_croplandfile)
  rm(hyde_cropland)
  gc()
} else {
  landuse_array_expanded <- faostat_env$landuse_array
}
