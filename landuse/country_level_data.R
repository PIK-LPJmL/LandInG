      datacols <- c(
        "Monfreda_GADM",
        "FAOSTAT",
        "Monfreda_GADM_flag_max",
        "Monfreda_GADM_fcropland",
        "Monfreda_GADM_fborder"
      )
      datacols2 <- c("Monfreda_GADM", "FAOSTAT")
      dummy <- rep(NA, length(datacols) - length(datacols2))

      writeLines(
        dQuote(
          paste(
            length(crops), "crops present",
            "according to both Monfreda (GADM aggregation) and FAOSTAT"
          )
        ),
        con = countrystats_file
      )
      if (length(crops_filtered) > 1) {
        write.csv(
          rbind(
            fao_mon_production_array[country, crops_filtered, year, datacols],
            sum = c(
              apply(
                fao_mon_production_array[country, crops_filtered, year, datacols2],
                "value",
                sum
              ),
              dummy
            )
          ),
          file = countrystats_file
        )
      } else {
        write.csv(
          cbind(
            dimnames(fao_mon_production_array)[["item"]][crops],
            t(fao_mon_production_array[country, crops, year, datacols2])
          ),
          file = countrystats_file,
          row.names = FALSE
        )
      }
      if (length(crops_filtered) < length(crops)) {
        filtered <- setdiff(crops, crops_filtered)
        writeLines(
          dQuote(
            paste(
              "Of those, the following",
              length(filtered),
              "Monfreda crop patterns appear to be artefacts.",
              "FAOSTAT values will be assigned to new patterns."
            )
          ),
          con = countrystats_file
        )
        if (length(filtered) > 1) {
          write.csv(
            rbind(
              fao_mon_production_array[country, filtered, year, datacols],
              sum = c(
                apply(
                  fao_mon_production_array[country, filtered, year, datacols2],
                  "value",
                  sum,
                  na.rm = TRUE
                ),
                dummy
              )
            ),
            file = countrystats_file
          )
        } else {
          write.csv(
            cbind(
              dimnames(fao_mon_production_array)[["item"]][filtered],
              t(fao_mon_production_array[country, filtered, year, datacols])
            ),
            file = countrystats_file,
            row.names = FALSE
          )
        }
      }
    }

    # Crops present only in FAOSTAT
    crops <- which(
      (
        is.na(fao_mon_production_array[country, , year, "Monfreda_GADM"]) |
          fao_mon_production_array[country, , year, "Monfreda_GADM"] == 0
      ) &
        fao_mon_production_array[country, , year, "FAOSTAT"] > 0
    )
    # Remove crop groups
    index <- which(
      !dimnames(fao_mon_production_array)[["item"]][crops] %in%
        unique(fao_production_item_group_def$Item.Group)
    )
    crops <- crops[index]
    if (length(crops) > 0) {
      datacols2 <- c("Monfreda_GADM", "FAOSTAT")
      writeLines(
        dQuote(
          paste(
            length(crops),
            "crops present according to FAOSTAT but missing in Monfreda"
          )
        ),
        con = countrystats_file
      )
      if (length(crops) > 1) {
        write.csv(
          rbind(
            fao_mon_production_array[country, crops, year, datacols2],
            sum = apply(
              fao_mon_production_array[country, crops, year, datacols2],
              "value",
              sum,
              na.rm = TRUE
            )
          ),
          file = countrystats_file
        )
      } else {
        write.csv(
          cbind(
            dimnames(fao_mon_production_array)[["item"]][crops],
            t(fao_mon_production_array[country, crops, year, datacols2])
          ),
          file = countrystats_file,
          row.names = FALSE
        )
      }
    }

    # Crops present only in Monfreda
    crops <- which(
      (
        is.na(fao_mon_production_array[country, , year, "FAOSTAT"]) |
          fao_mon_production_array[country, , year, "FAOSTAT"] == 0
      ) &
        fao_mon_production_array[country, , year, "Monfreda_GADM"] > 0
    )
    crops <- setdiff(
      crops,
      # Exclude crop groups
      match(
        unique(fao_production_item_group_def$Item.Group),
        dimnames(fao_mon_production_array)[["item"]]
      )
    )
    # Filter out crops just found along the border, probably artefacts of
    # country mask.
    index <- which(
      fao_mon_production_array[country, crops, year, "Monfreda_GADM_fborder"] <
        LandInG_setup$landuse$mon_threshold_border
    )
    crops_filtered <- crops[index]

    # Crop area in country must be at least 1 ha
    index <- which(
      fao_mon_production_array[country, crops_filtered, year, "Monfreda_GADM"] >= 1
    )
    crops_filtered <- crops_filtered[index]

    # Filter based on flag_max (best source resolution) and fcropland
    # Based on flag_max this filter computes the fcropland of the smallest
    # country/state/county in "country"
    for (c in crops_filtered) {
      datacol <- "Monfreda_GADM_flag_max"
      clevel <- ifelse(
        fao_mon_production_array[country, c, year, datacol] <= 0.25,
        1,
        ifelse(
          fao_mon_production_array[country, c, year, datacol] <= 0.75,
          2,
          3
        )
      )
      if (
        all(
          fao_mon_production_array[country, c, year, "Monfreda_GADM_fcropland"] <
            fcropland_threshold[clevel] &
            fao_mon_production_array[country, c, year, "Monfreda_GADM_fcropland"] > 0,
          na.rm = TRUE
        )
      ) {
        crops_filtered <- setdiff(crops_filtered, c)
      }
    }
    # Set fao_mon_use_pattern to TRUE for crops that have not been classified
    # as artefacts
    fao_mon_use_pattern[country, crops_filtered, year] <- TRUE

    if (length(crops) > 0) {
      datacols <- c(
        "Monfreda_GADM",
        "Monfreda_GADM_flag_max",
        "Monfreda_GADM_fcropland",
        "Monfreda_GADM_fborder"
      )
      datacols2 <- c("Monfreda_GADM")
      dummy <- rep(NA, length(datacols) - length(datacols2))
      writeLines(
        dQuote(
          paste(
            length(crops),
            "crops present according to Monfreda but missing in FAOSTAT"
          )
        ),
        con = countrystats_file
      )
      if (length(crops_filtered) > 1) {
        write.csv(
          rbind(
            fao_mon_production_array[country, crops_filtered, year, datacols],
            sum = c(
              sum(
                fao_mon_production_array[country, crops_filtered, year, datacols2],
                na.rm = TRUE
              ),
              dummy
            )
          ),
          file = countrystats_file
        )
      } else {
        write.csv(
          cbind(
            dimnames(fao_mon_production_array)[["item"]][crops_filtered],
            t(fao_mon_production_array[country, crops_filtered, year, datacols])
          ),
          file = countrystats_file,
          row.names = FALSE
        )
      }
      if (length(crops_filtered) < length(crops)) {
        filtered <- setdiff(crops, crops_filtered)
        writeLines(
          dQuote(
            paste(
              "Of those, the following", length(filtered),
              "Monfreda crops appear to be artefacts and will be dropped."
            )
          ),
          con = countrystats_file
        )
        if (length(filtered) > 1) {
          write.csv(
            rbind(
              fao_mon_production_array[country, filtered, year, datacols],
              sum = c(
                sum(
                  fao_mon_production_array[country, filtered, year, datacols2],
                  na.rm = TRUE
                ),
                dummy
              )
            ),
            file = countrystats_file
          )
        } else {
          write.csv(
            cbind(
              dimnames(fao_mon_production_array)[["item"]][filtered],
              t(fao_mon_production_array[country, filtered, year, datacols])
            ),
            file = countrystats_file,
            row.names = FALSE
          )
        }
      }
    }
  } # end year loop
} # end country loop
close(countrystats_file)

# Update Monfreda country sums based on filter operations above
# Remove all Monfreda values for countries/crops where fao_mon_use_pattern
# is FALSE
tmp_gadm <- fao_mon_production_array[, , , "Monfreda_GADM"]
index <- intersect(
