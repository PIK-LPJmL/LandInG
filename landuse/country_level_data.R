  ram_cropland <- terra::rast(LandInG_setup$landuse$ram_cropland_file)
  if (terra::nlyr(ram_cropland) != length(LandInG_setup$landuse$mon_refyear)) {
    stop(
      "Number of years in ", sQuote(LandInG_setup$landuse$ram_cropland_file),
      " (", terra::nlyr(ram_cropland), ") does not match mon_refyear ",
      toString(LandInG_setup$landuse$mon_refyear)
    )
  }
} else {
  stop(
    "Ramankutty cropland file does not exist.",
    "\nPlease check 'ram_cropland_file' in landuse_setup.R"
  )
}
if (matching_extent(
  terra::ext(ram_cropland),
  global_extent,
  terra::xres(ram_cropland),
  terra::yres(ram_cropland)
)) {
  terra::ext(ram_cropland) <- global_extent
}
# Unit conversion of Ramankutty cropland to Monfreda area unit or fao_area_units
# if Monfreda area unit is also fractional
if (ram_is_fraction) {
  # Fractional unit, multiply with area. Check HYDE area for compatibility
  if (matching_extent(
    terra::ext(ram_cropland),
    terra::ext(hyde_area),
    terra::xres(ram_cropland),
    terra::yres(ram_cropland)
  )) {
    if (all(terra::res(ram_cropland) == terra::res(hyde_area))) {
      cat(
        "Using hyde_area for ram_cropland because they share the same",
        "extent and resolution\n"
      )
      # Convert to fao_area_units using HYDE area
      terra::values(ram_cropland) <- terra::values(ram_cropland) *
        units::ud_convert(1, LandInG_setup$landuse$ram_units, "") *
        terra::values(hyde_area)
      LandInG_setup$landuse$ram_units <- terra::units(hyde_area)
      terra::units(ram_cropland) <- LandInG_setup$landuse$ram_units
    } else {
      # Ramankutty cropland has different resolution from HYDE area.
      # Generate cell area.
      cat(
        "Generating area for ram_cropland based on raster",
        "characteristics because Ramankutty resolution differs from other",
        "gridded data. Using calc_cellarea() function from lpjmlkit\n"
      )
      # Calculate cell areas for latitude coordinates
      ysize <- lpjmlkit::calc_cellarea(
        terra::yFromRow(ram_cropland),
        terra::xres(ram_cropland),
        terra::yres(ram_cropland),
        earth_radius = LandInG_setup$earthradius,
        return_unit = "m2"
      )
      # Unit conversion from m2 returned by calc_cellarea() to Monfreda area
      # unit or (if that is fractional) to FAOSTAT area unit
      target_unit <- ifelse(
        mon_is_fraction,
        LandInG_setup$landuse$fao_area_units,
        LandInG_setup$landuse$mon_area_units
      )
      ysize <- units::ud_convert(ysize, "m2", target_unit)
      # Expand to full grid
      gridsize <- rep(ysize, each = terra::ncol(ram_cropland))

      terra::values(ram_cropland) <- terra::values(ram_cropland) *
        units::ud_convert(1, LandInG_setup$landuse$ram_units, "") *
        gridsize
      LandInG_setup$landuse$ram_units <- target_unit
      terra::units(ram_cropland) <- target_unit
      rm(gridsize, ysize)
    }
  } else {
    # Ramankutty cropland has different spatial extent from HYDE area.
    # Generate cell area.
    cat(
      "Generating area for ram_cropland based on raster",
      "characteristics because Ramankutty resolution differs from other",
      "gridded data. Using calc_cellarea() function from lpjmlkit\n"
    )
    # Calculate cell areas for latitude coordinates
    ysize <- lpjmlkit::calc_cellarea(
      terra::yFromRow(ram_cropland),
      terra::xres(ram_cropland),
      terra::yres(ram_cropland),
      earth_radius = LandInG_setup$earthradius,
      return_unit = "m2"
    )
    # Unit conversion from m2 returned by calc_cellarea() to Monfreda area unit
    # or (if that is fractional) to FAOSTAT area unit
    target_unit <- ifelse(
      mon_is_fraction,
      LandInG_setup$landuse$fao_area_units,
      LandInG_setup$landuse$mon_area_units
    )
    ysize <- units::ud_convert(ysize, "m2", target_unit)
    # Expand to full grid
    gridsize <- rep(ysize, each = terra::ncol(ram_cropland))

    terra::values(ram_cropland) <- terra::values(ram_cropland) *
      units::ud_convert(1, LandInG_setup$landuse$ram_units, "") *
      gridsize
    LandInG_setup$landuse$ram_units <- target_unit
    terra::units(ram_cropland) <- target_unit
    rm(gridsize, ysize)
  }
} else {
  # Unit conversion from Ramankutty area unit to Monfreda area unit or
  # (if that is fractional) to FAOSTAT area unit
  target_unit <- ifelse(
    mon_is_fraction,
    LandInG_setup$landuse$fao_area_units,
    LandInG_setup$landuse$mon_area_units
  )
  terra::values(ram_cropland) <- terra::values(ram_cropland) *
    units::ud_convert(1, LandInG_setup$landuse$ram_units, target_unit)
  LandInG_setup$landuse$ram_units <- target_unit
  terra::units(ram_cropland) <- target_unit
}
ram_is_fraction <- !units::ud_are_convertible(
  LandInG_setup$landuse$ram_units,
  "m2"
)
################################################################################

################################################################################
## Aggregate Monfreda to FAO countries using GADM country mask                ##
## The resulting array has the dimensions country, crop, reference year(s)    ##
## Since grid-to-country aggregation takes quite long, results are stored in  ##
## RData file mon_gadm_sums_RData and not calculated again if that file  ##
## exists. Note that different versions of FAOSTAT may include different      ##
## countries so this depends on the FAOSTAT version used.                     ##
cat(
  "*** Aggregating Monfreda harvested areas to country sums using GADM",
  "country mask ***\n"
)
# Determine filenames of Monfreda source files
mon_filenames <- character(length(LandInG_setup$landuse$mon_names))
names(mon_filenames) <- LandInG_setup$landuse$mon_names
for (crop in LandInG_setup$landuse$mon_names) {
  tmpnames <- file.path(
    dir(
      file.path(
        LandInG_setup$landuse$mon_datadir[LandInG_setup$landuse$mon_fmt]
      ),
      pattern = paste0("^", crop, "_HarvAreaYield"),
      full.names = TRUE
    ),
    paste0(
      crop, "_",
      LandInG_setup$landuse$mon_file_var[[LandInG_setup$landuse$mon_fmt]][1],
      ".",
      LandInG_setup$landuse$mon_file_ext[LandInG_setup$landuse$mon_fmt]
    )
  )
  if (length(which(file.exists(tmpnames))) != 1) {
    stop(
      "Cannot determine filename for crop ", sQuote(crop), ".\n",
      "Tested filename(s): ", toString(tmpnames)
    )
  }
  mon_filenames[crop] <- tmpnames[which(file.exists(tmpnames))]
  rm(tmpnames)
}
# Check that extent and resolution match (including the need to aggregate
# Monfreda data)
mon_raster <- terra::rast(mon_filenames[1])
if (matching_extent(
  terra::ext(mon_raster),
  global_extent,
  terra::xres(mon_raster),
  terra::yres(mon_raster)
)) {
  terra::ext(mon_raster) <- global_extent
}
# Determine aggregation factor
if (
  any(
    terra::res(mon_raster) < terra::res(LandInG_setup$landuse$gadm_raster)
  )
) {
  mon2gadm <- round(
    terra::res(LandInG_setup$landuse$gadm_raster) / terra::res(mon_raster),
    4
  )
  if (max(mon2gadm %% 1) != 0) {
    stop(
      "GADM resolution ",
      toString(round(terra::res(LandInG_setup$landuse$gadm_raster), 5)),
      " is not compatible with Monfreda resolution ",
      toString(round(terra::res(mon_raster), 5))
    )
  }
  # Generate area raster corresponding to Monfreda source resolution
  cat(
    "Generating mon_area based on raster characteristics because",
    "Monfreda resolution differs from other gridded data.",
    "Using calc_cellarea() function from lpjmlkit\n"
  )
  mon_area <- terra::rast(mon_raster)
  # Calculate cell areas for latitude coordinates
  ysize <- lpjmlkit::calc_cellarea(
    terra::yFromRow(mon_area),
    terra::xres(mon_area),
    terra::yres(mon_area),
    earth_radius = LandInG_setup$earthradius,
    return_unit = "m2"
  )
  # Unit conversion from m2 to Monfreda area unit or (if that is fractional) to
  # FAOSTAT area unit
  target_unit <- ifelse(
    mon_is_fraction,
    LandInG_setup$landuse$fao_area_units,
    LandInG_setup$landuse$mon_area_units
  )
  ysize <- units::ud_convert(ysize, "m2", target_unit)
  # Expand to full grid
  gridsize <- rep(ysize, each = terra::ncol(mon_area))

  terra::set.values(
    mon_area,
    cells = seq_len(terra::ncell(mon_area)),
    values = gridsize
  )
  mon_area_file_units <- target_unit
  terra::units(mon_area) <- target_unit
  rm(gridsize, ysize)
} else if (
  any(terra::res(mon_raster) > terra::res(LandInG_setup$landuse$gadm_raster))
) {
  # Monfreda has coarser resolution than GADM. Generated landuse dataset cannot
  # be finer than any of the source datasets.
  stop(
    "GADM resolution ",
    toString(round(terra::res(LandInG_setup$landuse$gadm_raster), 5)),
    " is too fine for Monfreda resolution ",
    toString(round(terra::res(mon_raster), 5)), ".\n",
    "You need to create a gridded GADM mask at the Monfreda resolution."
  )
} else {
  # Monfreda has same resolution as GADM. Use HYDE area which has been
  # aggregated to GADM resolution above.
  mon2gadm <- c(1, 1)
  cat("Using HYDE area for Monfreda because they share the same resolution\n")
  # Unit conversion from HYDE area unit to Monfreda area unit or
  # (if that is fractional) to FAOSTAT area unit
  target_unit <- ifelse(
    mon_is_fraction,
    LandInG_setup$landuse$fao_area_units,
    LandInG_setup$landuse$mon_area_units
  )
  mon_area <- hyde_area * units::ud_convert(
    1,
    terra::units(hyde_area),
    target_unit
  )
  mon_area_file_units <- target_unit
  terra::units(mon_area) <- target_unit
}
# mon_gadm_production_array contains harvested areas aggregated to countries.
# mon_gadm_quality_array contains information that is used to detect artefacts
# that result from a mismatch between GADM used here and the mask used to create
# the Monfreda dataset.
mon_gadm_production_array <- array(
  dim = c(
    country = length(LandInG_setup$landuse$fao_gadm_country_mapping),
    item = length(LandInG_setup$landuse$mon_names),
    time = length(LandInG_setup$landuse$mon_refyear)
  ),
  dimnames = list(
    country = names(LandInG_setup$landuse$fao_gadm_country_mapping),
    item = LandInG_setup$landuse$mon_names,
    time = LandInG_setup$landuse$mon_refyear
  )
)
mon_gadm_quality_array <- array(
  dim = c(dim(mon_gadm_production_array), flag = 3),
  dimnames = c(
    dimnames(mon_gadm_production_array),
    flag = list(c("flag_max", "fcropland", "fborder"))
  )
)
if (file.exists(LandInG_setup$landuse$mon_gadm_sums_RData)) {
  # Since aggregation to countries takes quite long results are saved and
  # reused if this script is run again. Delete file mon_gadm_sums_RData if you
  # want to force it to be calculated again.
  cat(
    "Reloading preprocessed Monfreda harvested area sums from",
    sQuote(LandInG_setup$landuse$mon_gadm_sums_RData), "\n"
  )
  load(LandInG_setup$landuse$mon_gadm_sums_RData)
  if (
    !exists("LandInG_version") ||
      LandInG_version != LandInG_setup$LandInG_version
  ) {
    stop(
      "Preprocessed Monfreda harvested area sums in ",
      sQuote(LandInG_setup$landuse$mon_gadm_sums_RData),
      "were generated with a different version of LandInG.\n",
      "Delete file to process again."
    )
  }
  rm(LandInG_version)
  # Unwrap SpatRaster objects
  if (is(ram_gadm_cropland, "PackedSpatRaster")) {
    ram_gadm_cropland <- terra::unwrap(ram_gadm_cropland)
  }
  if (is(mon_area, "PackedSpatRaster")) {
    mon_area <- terra::unwrap(mon_area)
  }
} else {
  if (exists("mon_harvest_sum")) {
    rm(mon_harvest_sum)
  }
  if (exists("kapok_mon_filedata")) {
    rm(kapok_mon_filedata)
  }
  cat("Associating GADM grid cells with FAO countries\n")
  fao_gadm_country_cells <- list()
  # Extract country IDs from gadmlevel_raster
  tmpcodes <- terra::values(gadmlevel_raster[[1]], mat = FALSE)
  for (country in names(LandInG_setup$landuse$fao_gadm_country_mapping)) {
    # Find ISO code(s) in gadm_country_names
    index <- match(
      LandInG_setup$landuse$fao_gadm_country_mapping[[country]],
      gadm_country_names$level0_code
    )
    # Find IDs used in gadmlevel_raster matching ISO codes
    ccodes <- gadm_country_names[index, "level0_ID"]
    # Find cell indices with matching ID
    fao_gadm_country_cells[[country]] <- which(tmpcodes %in% ccodes)
  }
  rm(tmpcodes)
  # GADM border data: Has for each cell the number of countries in it.
  # Duplicate data so that it is available for all mon_refyear.
  gadmborder_data <- array(
    rep(
      terra::values(gadmborder_raster, mat = FALSE),
      length(LandInG_setup$landuse$mon_refyear)
    ),
    dim = c(
      cell = terra::ncell(gadmborder_raster),
      time = length(LandInG_setup$landuse$mon_refyear)
    ),
    dimnames = list(
      cell = NULL,
      time = LandInG_setup$landuse$mon_refyear
    )
  )
  cat(
    "Aggregating Monfreda harvested areas for",
    length(LandInG_setup$landuse$mon_names), "crops to",
    length(fao_gadm_country_cells),
    "FAO countries and country groups\n"
  )
  for (crop in LandInG_setup$landuse$mon_names) {
    if (which(LandInG_setup$landuse$mon_names == crop) %% 10 == 0) {
      # Status prompt every 10 crops
      cat(
        which(LandInG_setup$landuse$mon_names == crop), "of",
        length(LandInG_setup$landuse$mon_names), "\n"
      )
    }
    if (!file.exists(mon_filenames[crop])) {
      warning(
        "Missing input file ",
        sQuote(mon_filenames[crop]),
        " for Monfreda crop ", sQuote(crop),
        call. = FALSE,
        immediate. = TRUE
      )
      next
    }
    if (!exists("mon_area")) {
      warning(
        "No cell area available for Monfreda. Deriving using ",
        "calc_cellarea() function from lpjmlkit",
        call. = FALSE,
        immediate. = TRUE
      )
      mon_area <- terra::rast(mon_filenames[crop], lyrs = 1)
      # Calculate cell areas for latitude coordinates
      ysize <- lpjmlkit::calc_cellarea(
        terra::yFromRow(mon_area),
        terra::xres(mon_area),
        terra::yres(mon_area),
        earth_radius = LandInG_setup$earthradius,
        return_unit = "m2"
      )
      # Unit conversion from m2 returned by calc_cellarea() to Monfreda area
      # unit or (if that is fractional) to FAOSTAT area unit
      target_unit <- ifelse(
        mon_is_fraction,
        LandInG_setup$landuse$fao_area_units,
        LandInG_setup$landuse$mon_area_units
      )
      ysize <- units::ud_convert(ysize, "m2", target_unit)
      # Expand to full grid
      gridsize <- rep(ysize, each = terra::ncol(mon_area))
      terra::set.values(
        mon_area,
        cells = seq_len(terra::ncell(mon_area)),
        values = gridsize
      )
      mon_area_file_units <- target_unit
      terra::units(mon_area) <- target_unit
      rm(gridsize, ysize)
    }
    # Function get_crop_monfreda() is defined in helper/get_crop_monfreda.R
    # This function aggregates Monfreda data to GADM resolution if necessary.
    loaded_fields <- get_crop_monfreda(
      filename = mon_filenames[crop],
      file_format = LandInG_setup$landuse$mon_fmt,
      file_area_layer = LandInG_setup$landuse$mon_area_layer,
      file_quality_layer = LandInG_setup$landuse$mon_area_quality_layer,
      file_is_fraction = mon_is_fraction,
      file_var = LandInG_setup$landuse$mon_file_var,
      file_units = LandInG_setup$landuse$mon_area_units,
      file_years = LandInG_setup$landuse$mon_refyear,
      crop = crop,
      unit_raster = LandInG_setup$landuse$gadm_raster,
      fact = mon2gadm,
      global_cover = global_extent,
      area_raster = mon_area,
      crop_names = LandInG_setup$landuse$mon_names
    )
    mon_filedata <- loaded_fields[["filedata"]]
    mon_qualitydata <- loaded_fields[["qualitydata"]]
    rm(loaded_fields)
    # If necessary, aggregate also Ramankutty cropland to GADM resolution
    if (!exists("ram_gadm_cropland")) {
      target_unit <- ifelse(
        mon_is_fraction,
        mon_area_file_units,
        LandInG_setup$landuse$mon_area_units
      )
      if (max(mon2gadm) > 1) {
        # Aggregate Ramankutty cropland to GADM resolution and convert unit
        ram_gadm_cropland <- terra::aggregate(
          ram_cropland,
          fact = rev(mon2gadm), # res() returns lon/lat, fact is lat/lon
          fun = "sum",
          na.rm = TRUE
        ) * units::ud_convert(
          1,
          terra::units(ram_cropland),
          target_unit
        )
      } else {
        # Convert only unit
        ram_gadm_cropland <- ram_cropland *
          units::ud_convert(
            1,
            terra::units(ram_cropland),
            target_unit
          )
      }
      terra::units(ram_gadm_cropland) <- target_unit
    }
    # Filter very small values
    tiny <- which(mon_filedata < LandInG_setup$landuse$mon_cutoff)
    mon_filedata[tiny] <- 0
    rm(tiny)
    # Kapok fix:
    # Monfreda has harvested areas for kapokfiber and kapokseed which are both
    # harvested from Kapok fruit (found in FAOSTAT)
    # Do not add them twice to mon_harvest_sum IF harvested areas are
    # identical (which they seem to be in the current version of Monfreda)
    skip_sum <-  FALSE
    if (grepl("kapok", crop)) {
      if (exists("kapok_mon_filedata")) {
        skip_sum <- identical(kapok_mon_filedata, mon_filedata)
      } else {
        kapok_mon_filedata <- mon_filedata
      }
    }
    if (skip_sum) {
      cat(
        "Not adding", sQuote(crop),
        "to mon_harvest_sum because it is identical to",
        sQuote(
          setdiff(
            grep("kapok", LandInG_setup$landuse$mon_names, value = TRUE),
            crop
          )
        ), "\n"
      )
    }
    if (!exists("mon_harvest_sum")) {
      mon_harvest_sum <- mon_filedata
    } else if (!skip_sum) {
      mon_harvest_sum <- ifelse(
        is.na(mon_harvest_sum),
        # Set to mon_filedata if sum is still NA
        mon_filedata,
        ifelse(
          is.na(mon_filedata),
          # Keep old sum if mon_filedata is NA
          mon_harvest_sum,
          # Otherwise add values to sum
          mon_harvest_sum + mon_filedata
        )
      )
    }
    if (length(dim(mon_filedata)) == 2) {
      # Dissolve separate lon and lat dimensions and set time dimension.
      dim(mon_filedata) <- c(
        cell = ncol(mon_filedata) * nrow(mon_filedata),
        time = 1
      )
      dimnames(mon_filedata) <- list(
        cell = NULL,
        time = LandInG_setup$landuse$mon_refyear
      )
      dim(mon_qualitydata) <- dim(mon_filedata)
      dimnames(mon_qualitydata) <- dimnames(mon_filedata)
    } else {
      # Dissolve separate lon and lat dimensions.
      dim(mon_filedata) <- c(
        cell = ncol(mon_filedata) * nrow(mon_filedata),
        time = dim(mon_filedata)["time"]
      )
      dimnames(mon_filedata) <- list(
        cell = NULL,
        time = LandInG_setup$landuse$mon_refyear
      )
      dim(mon_qualitydata) <- dim(mon_filedata)
      dimnames(mon_qualitydata) <- dimnames(mon_filedata)
    }
    # Collect some statistics used to detect possible artefacts due to
    # mismatches in country masks.
    # "flag_max" is the highest data quality flag found in the country.
    # "fcropland" is the fraction of cropland cells in the country that the crop
    # is present in.
    # "fborder" is the fraction of cells where the crop is present that are also
    # border cells (contain parts of more than one country)
    for (country in dimnames(mon_gadm_production_array)[["country"]]) {
      if (length(fao_gadm_country_cells[[country]]) == 0) {
        # FAOSTAT country has no assigned GADM units, therefore no assigned
        # cells
        next
      }
      mon_gadm_production_array[country, crop, ] <- apply(
        mon_filedata[fao_gadm_country_cells[[country]], , drop = FALSE],
        "time",
        sum,
        na.rm = TRUE
      )
      mon_gadm_quality_array[country, crop, , "fborder"] <- apply(
        mon_filedata[fao_gadm_country_cells[[country]], , drop = FALSE] > 0 &
          gadmborder_data[fao_gadm_country_cells[[country]], , drop = FALSE] > 1,
        "time",
        sum,
        na.rm = TRUE
      ) / apply(
        mon_filedata[fao_gadm_country_cells[[country]], , drop = FALSE] > 0,
        "time",
        sum,
        na.rm = TRUE
      )
      mon_gadm_quality_array[country, crop, , "fborder"] <- ifelse(
        is.finite(mon_gadm_quality_array[country, crop, , "fborder"]),
        mon_gadm_quality_array[country, crop, , "fborder"],
        1
      )
      for (year in seq_along(LandInG_setup$landuse$mon_refyear)) {
        cropland_country_cells <- which(
          ul(ram_gadm_cropland[[year]][fao_gadm_country_cells[[country]]]) > 0
        )
        if (all(is.na(mon_filedata[fao_gadm_country_cells[[country]], year]))) {
          mon_gadm_production_array[country, crop, year] <- NA
        }
        if (length(cropland_country_cells) > 0) {
          # Index of Ramankutty cropland cells in GADM raster
          index <- fao_gadm_country_cells[[country]][cropland_country_cells]
          if (all(is.na(mon_qualitydata[index, year]))) {
            mon_gadm_quality_array[country, crop, year, "flag_max"] <- NA
          } else {
            mon_gadm_quality_array[country, crop, year, "flag_max"] <- max(
              mon_qualitydata[index, year],
              na.rm = TRUE
            )
          }
          if (all(is.na(mon_filedata[index, year]))) {
            mon_gadm_quality_array[country, crop, year, "fcropland"] <- -1
          } else {
            mon_gadm_quality_array[country, crop, year, "fcropland"] <-
              length(which(mon_filedata[index, year] > 0)) /
              length(cropland_country_cells)
          }
        } else {
          mon_gadm_quality_array[country, crop, year, "flag_max"] <- NA
          mon_gadm_quality_array[country, crop, year, "fcropland"] <- -1
        }
      }
    }
  }
  # Save to RData file
  # Need to wrap SpatRaster objects
  ram_gadm_cropland <- terra::wrap(ram_gadm_cropland)
  mon_area <- terra::wrap(mon_area)
  LandInG_version <- LandInG_setup$LandInG_version
  save(
    mon_gadm_production_array,
    mon_gadm_quality_array,
    ram_gadm_cropland,
    mon_harvest_sum,
    fao_gadm_country_cells,
