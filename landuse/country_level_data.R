        ifelse(
          is.na(fao_production_country_def$End.Year[index]),
          "",
          paste0(
            " (ceases to exist in ",
            fao_production_country_def$End.Year[index],
            ")"
          )
        ),
        " ***"
      )
    ),
    con = countrystats_file
  )
  # Loop over Monfreda reference years for filtering.
  for (year in seq_along(LandInG_setup$landuse$mon_refyear)) {
    if (length(LandInG_setup$landuse$mon_refyear) > 1) {
      writeLines(
        dQuote(
          paste("Reference year:", LandInG_setup$landuse$mon_refyear[year])
        ),
        con = countrystats_file
      )
    }
    # Crops present in both datasets
    crops <- setdiff(
      which(
        fao_mon_production_array[country, , year, "Monfreda_GADM"] > 0 &
          fao_mon_production_array[country, , year, "FAOSTAT"] > 0
      ),
      # Exclude crop groups
      match(
        unique(fao_production_item_group_def$Item.Group),
        dimnames(fao_mon_production_array)[["item"]]
      )
    )
    # Filter out crops only found along the border, probably artefacts of
    # country mask.
    index <- which(
      fao_mon_production_array[country, crops, year, "Monfreda_GADM_fborder"] <
        LandInG_setup$landuse$mon_threshold_border
    )
    crops_filtered <- crops[index]

    # Crop area in country must be at least 1 ha
    index <- which(
      fao_mon_production_array[country, crops_filtered, year, "Monfreda_GADM"] >= 1
    )
    crops_filtered <- crops_filtered[index]

    # Filter based on flag_max (best source resolution) and fcropland
    # Based on flag_max this filter computes the fcropland of the smallest
    # country/state/county in "country"
    fcropland_threshold <- double(3)
    cropland_country_cells <- which(
      ram_gadm_cropland[[year]][fao_gadm_country_cells[[country]]] > 0
    )
    for (clevel in seq_len(3)) {
      # Find the fcropland of the smallest country/region/county in "country"
      # Allow 25% tolerance because GADM versions do not match
      fcropland_threshold[clevel] <- min(
        rle(
          sort(
            ifelse(
              ul(
                ram_gadm_cropland[[year]][fao_gadm_country_cells[[country]]]
              ) > 0,
              ul(
                gadmlevel_raster[[clevel]][fao_gadm_country_cells[[country]]]
              ),
              NA
            )
          )
        )$lengths
      ) / length(cropland_country_cells) * 0.75
    }
    for (c in crops_filtered) {
      datacol <- "Monfreda_GADM_flag_max"
      clevel <- ifelse(
        fao_mon_production_array[country, c, year, datacol] <= 0.25,
        1,
        ifelse(
          fao_mon_production_array[country, c, year, datacol] <= 0.75,
          2,
          3
        )
      )
      if (
        all(
          fao_mon_production_array[country, c, year, "Monfreda_GADM_fcropland"] <
            fcropland_threshold[clevel] &
            fao_mon_production_array[country, c, year, "Monfreda_GADM_fcropland"] > 0,
          na.rm = TRUE
        )
      ) {
        crops_filtered <- setdiff(crops_filtered, c)
      }
    }
    # Set fao_mon_use_pattern to TRUE for crops that have not been classified
    # as artefacts
    fao_mon_use_pattern[country, crops_filtered, year] <- TRUE

    # Provide extensive information on crops present in both or crops present in
