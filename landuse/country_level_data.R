  which(fao_mon_use_pattern == FALSE)
)
tmp_gadm[index] <- 0
fao_mon_production_array[, , , "Monfreda_GADM"] <- tmp_gadm

# Count number of crops present in crop groups according to FAOSTAT and Monfreda
# and update group sums
fao_mon_production_group_members <- array(
  dim = c(
    country = dim(fao_mon_production_array)[1],
    group = length(fao_production_item_group_def_usable),
    time = length(LandInG_setup$landuse$mon_refyear),
    dataset = 2
  ),
  dimnames = list(
    country = dimnames(fao_mon_production_array)[["country"]],
    group = fao_production_item_group_def_usable,
    time = as.character(LandInG_setup$landuse$mon_refyear),
    dataset = c("Monfreda_GADM", "FAOSTAT")
  )
)
if (length(LandInG_setup$landuse$mon_refyear) > 1) {
  crop_sum_dims <- c("country", "time")
} else {
  crop_sum_dims <- c("country")
}
for (group in fao_production_item_group_def_usable) {
  if (!group %in% dimnames(fao_mon_production_array)[["item"]]) {
    next
  }
  index <- which(fao_production_item_group_def$Item.Group == group)
  crops <- intersect(
    dimnames(fao_mon_production_array)[["item"]],
    fao_production_item_group_def$Item[index]
  )
  # Countries without country groups
  clist <- setdiff(
    dimnames(fao_mon_production_array)[["country"]],
    names(fao_groups)
  )
  fao_mon_production_array[clist, group, , "Monfreda_GADM"] <- apply(
    fao_mon_production_array[clist, crops, , "Monfreda_GADM"],
    crop_sum_dims,
    sum,
    na.rm = TRUE
  )
  fao_mon_production_group_members[clist, group, , "Monfreda_GADM"] <-
    apply(
      fao_mon_production_array[clist, crops, , "Monfreda_GADM"],
      crop_sum_dims,
      function(x) length(which(x > 0))
    )
  fao_mon_production_group_members[clist, group, , "FAOSTAT"] <- apply(
    fao_mon_production_array[clist, crops, , "FAOSTAT"],
    crop_sum_dims,
    function(x) length(which(!is.na(x)))
  )
}
