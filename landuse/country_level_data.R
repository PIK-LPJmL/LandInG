        "Adding",
        toString(
          sQuote(
            setdiff(
              grep(
                "Cyprus",
                names(LandInG_setup$landuse$fao_gadm_country_mapping),
                value = TRUE,
                ignore.case = TRUE
              ),
              faostat_env$production_countries$NAME
            )
          )
        ),
        "to FAOSTAT production data\n"
      )
      # Expand production_array
      index <- match(
        c(dimnames(faostat_env$production_array)[["country"]],
          setdiff(
            grep(
              "Cyprus",
              names(LandInG_setup$landuse$fao_gadm_country_mapping),
              value = TRUE,
              ignore.case = TRUE
            ),
            dimnames(faostat_env$production_array)[["country"]]
          )
        ),
