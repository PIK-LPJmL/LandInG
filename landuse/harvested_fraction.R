## Load HYDE data                                                             ##
# HYDE area file is aggregated to the resolution of unitraster if necessary
hyde_area <- load_hyde_area(
  filename = LandInG_setup$landuse$hyde_area_file,
  fileunits = LandInG_setup$landuse$hyde_area_file_units,
  return_units = LandInG_setup$landuse$fao_area_units,
  return_raster = NULL, # set to NULL to get native HYDE resolution
  earth_radius = LandInG_setup$earthradius,
  gextent = global_extent
)
hyde_area <- hyde_area$area
if (matching_extent(
  terra::ext(hyde_area),
  terra::ext(country_env$ram_gadm_cropland),
  terra::xres(hyde_area),
  terra::yres(hyde_area)
)) {
  hyde2gadm <- round(
    terra::res(country_env$ram_gadm_cropland) / terra::res(hyde_area),
    4
  )
  if (max(hyde2gadm %% 1) != 0) {
    stop(
      "Target resolution ",
      toString(round(terra::res(country_env$ram_gadm_cropland), 5)),
      " is not an integer multiple of HYDE resolution ",
      toString(round(terra::res(hyde_area), 5)), "\n",
      "Cannot aggregate."
    )
  }
  if (min(hyde2gadm) < 1) {
    stop(
      "Target resolution ",
      toString(round(terra::res(country_env$ram_gadm_cropland), 5)),
      " is finer than HYDE resolution ",
      toString(round(terra::res(hyde_area), 5)), "\n",
      "Output resolution cannot be finer than any gridded source data."
    )
  } else if (max(hyde2gadm) == 1) {
    hyde_target_area <- hyde_area
  } else {
    hyde_target_area <- terra::aggregate(
      hyde_area,
      fact = rev(hyde2gadm), # res() returns lon/lat, fact is lat/lon
      fun = "sum",
      na.rm = TRUE
    )
    terra::units(hyde_target_area) <- terra::units(hyde_area)
    if (
      !isTRUE(
        all.equal(
          terra::global(hyde_target_area, "sum", na.rm = TRUE),
          terra::global(hyde_area, "sum", na.rm = TRUE)
        )
      )
    ) {
      # Global area sum before and after aggregation do not match
      stop("Error aggregating hyde_area to target resolution")
    }
  }
} else {
  stop(
    "Spatial extent of ", sQuote(LandInG_setup$landuse$hyde_area_file),
    " does not match spatial extent of Ramankutty cropland/Monfreda",
    " harvested areas"
  )
}
# HYDE maximum cropland extent
# Maximum cropland is saved to file to reduce runtime if the script is run
# again for the same resolution and time period
if (!file.exists(LandInG_setup$landuse$hyde_max_cropland_filename)) {
  # Create file if it does not exist yet
  # This requires CDO tools to be installed and accessible. Syntax in
  # helper/create_hyde_timeseries_max.R is for Linux.
  create_hyde_timeseries_max(
    source = LandInG_setup$landuse$hyde_cropland_filename,
    target = LandInG_setup$landuse$hyde_max_cropland_filename,
    varname = LandInG_setup$landuse$hyde_cropland_varname,
    sourcearea = hyde_area,
    targetarea = hyde_target_area,
    area_units = LandInG_setup$landuse$hyde_area_units
  )
}
if (file.exists(LandInG_setup$landuse$hyde_max_cropland_filename)) {
  cat(
    "Loading maximum cropland extent from",
    sQuote(LandInG_setup$landuse$hyde_max_cropland_filename), "\n"
  )
  hyde_max_cropland <-
    terra::rast(LandInG_setup$landuse$hyde_max_cropland_filename)
  unit <- terra::units(hyde_max_cropland)
  if (units::ud_convert(1, LandInG_setup$landuse$hyde_area_units, unit) != 1) {
    warning(
      "Unit in file ", sQuote(LandInG_setup$landuse$hyde_max_cropland_filename),
      " [", unit, "] differs from defined hyde_area_units [",
      LandInG_setup$landuse$hyde_area_units,
      "].",
      call. = FALSE,
      immediate. = TRUE
    )
    # update unit
    LandInG_setup$landuse$hyde_area_units <- unit
    hyde_is_fraction <-
      !units::ud_are_convertible(LandInG_setup$landuse$hyde_area_units, "m2")
  }
  if (hyde_is_fraction) {
    hyde_max_cropland <- hyde_max_cropland *
      units::ud_convert(1, LandInG_setup$landuse$hyde_area_units, "1") *
      hyde_target_area
    terra::units(hyde_max_cropland) <- terra::units(hyde_target_area)
  } else {
    hyde_max_cropland <- hyde_max_cropland *
      units::ud_convert(1, unit, LandInG_setup$landuse$fao_area_units)
    terra::units(hyde_max_cropland) <- LandInG_setup$landuse$fao_area_units
  }
} else {
  stop(
    sQuote(LandInG_setup$landuse$hyde_max_cropland_filename),
    " does not exist and cannot be created automatically."
  )
}
